CREATE TABLE loads (
    id BIGINT AUTO_INCREMENT PRIMARY KEY,
    public_id BINARY(16) NOT NULL,
    publisher_user_id BIGINT NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'PUBLISHED',
    origin_department VARCHAR(100) NOT NULL,
    origin_city VARCHAR(100) NOT NULL,
    origin_address VARCHAR(255) NULL,
    pickup_date_utc DATETIME(6) NOT NULL,
    destination_department VARCHAR(100) NOT NULL,
    destination_city VARCHAR(100) NOT NULL,
    destination_address VARCHAR(255) NULL,
    delivery_date_utc DATETIME(6) NOT NULL,
    product_type VARCHAR(100) NOT NULL,
    weight_kg DECIMAL(10,2) NOT NULL,
    volume_m3 DECIMAL(10,2) NULL,
    packaging_type VARCHAR(100) NULL,
    requires_refrigeration BOOLEAN NOT NULL DEFAULT FALSE,
    vehicle_type VARCHAR(100) NOT NULL,
    body_type VARCHAR(100) NOT NULL,
    pricing_type VARCHAR(32) NOT NULL DEFAULT 'OFFERED',
    offered_price DECIMAL(12,2) NULL,
    payer VARCHAR(64) NOT NULL DEFAULT 'REMITTENT',
    special_instructions TEXT NULL,
    created_at_utc DATETIME(6) NOT NULL,
    updated_at_utc DATETIME(6) NOT NULL,
    CONSTRAINT uk_loads_public_id UNIQUE (public_id),
    CONSTRAINT fk_loads_publisher FOREIGN KEY (publisher_user_id) REFERENCES users (id),
    INDEX idx_loads_status (status),
    INDEX idx_loads_publisher (publisher_user_id),
    INDEX idx_loads_origin_destination (origin_city, destination_city)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
